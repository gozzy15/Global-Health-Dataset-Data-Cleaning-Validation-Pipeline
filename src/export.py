"""
Utilities for exporting cleaned data and validation reports.

This module handles persistence of outputs generated by the
Global Health Dataset cleaning pipeline.
"""

from pathlib import Path

import pandas as pd


def save_cleaned_data(
    df: pd.DataFrame,
    output_path: str,
) -> dict:
    """
    Save the cleaned dataset to a CSV file.

    The parent directory is created automatically if it
    does not already exist.

    Parameters
    ----------
    df : pandas.DataFrame
        Cleaned dataset to export.

    output_path : str
        Destination path for the cleaned CSV file.

    Returns
    -------
    dict
        Export report containing the output path and
        dataset dimensions.

    Raises
    ------
    ValueError
        If the DataFrame is empty.
    """

    if df.empty:
        raise ValueError(
            "Cannot export an empty DataFrame."
        )

    path = Path(output_path)

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    df.to_csv(
        path,
        index=False,
    )

    return {
        "Output Path": str(path),
        "Rows": len(df),
        "Columns": len(df.columns),
    }


